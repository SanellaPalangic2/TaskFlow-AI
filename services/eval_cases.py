# --- Hard cases ---------------------------------------------------------------------------------------
# Written to try to break the analysis, not to make it look good. Each one targets a specific failure:
#   contradictory notes   the customer's words disagree with the record (or with themselves)
#   vague intent          too little to act on; the right answer is "Unclear" and a clarifying step
#   missing documents     required items the model must report, including ones the customer claims to have sent
#   present documents     items already on file that the model must NOT report as missing
#   adversarial           prompt injection in the notes, and pressure for safety, price or legal judgments
#   multi-intent          two requests at once, cancellations, and a non-owner asking
# `expected.human_review: True` adds a fourth check: the model must set requires_human_review.
# Expected values were written before any run and are not tuned to the model's answers.

def _p(first, service, notes, roof_age=8, bill=200, stage="Information Gathering", status="Active",
       priority="Medium", email="on-file", phone="on-file", address="on-file"):
    """A fictional project record with ordinary defaults, so each case shows only what is unusual."""
    return {"first_name": first, "last_name": "Test", "service_type": service, "monthly_electric_bill": bill,
            "roof_age": roof_age, "current_stage": stage, "project_status": status, "priority": priority,
            "email": email, "phone": phone, "address": address, "notes": notes}


def _hard(key, title, summary, tags, project, documents, intent, departments, action_label,
          information=(), must_not_claim=(), human_review=False):
    expected = {"intent": list(intent), "information": list(information), "must_not_claim": list(must_not_claim),
                "departments": list(departments), "action_label": action_label}
    if human_review:
        expected["human_review"] = True
    return {"key": key, "title": title, "summary": summary, "tier": "hard", "tags": list(tags),
            "project": project, "documents": documents, "expected": expected}


